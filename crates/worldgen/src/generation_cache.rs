//! Bounded generation caches: per-worker maps plus one shared map of chunk
//! column footprints. Workers that miss on the same footprint share its rows
//! between them instead of waiting for one worker to sample all of it.
use super::{BushProfile, ColumnSample, TreeProfile, WorldSampleConfig, deadwood::FallenTrunk};
use std::cell::RefCell;
use std::sync::atomic::{AtomicBool, AtomicUsize, Ordering};
use std::sync::{Arc, Mutex, OnceLock, Weak};
use engine_core::fast_hash::{FastBuild, FastMap};

#[derive(Default)]
struct Cache {
    cfg: Option<WorldSampleConfig>,
    columns: FastMap<(i32, i32), ColumnSample>,
    trees: FastMap<(i32, i32), Option<TreeProfile>>,
    bushes: FastMap<(i32, i32), Option<BushProfile>>,
    deadwood: FastMap<(i32, i32), Option<FallenTrunk>>,
    flora_trees: FastMap<(i32, i32), Option<super::flora::TreeSite>>,
}
thread_local! { static CACHE: RefCell<Cache> = RefCell::new(Cache::default()); }

macro_rules! cached {
    ($name:ident, $field:ident, $value:ty, $calculate:path, $limit:expr) => {
        pub(super) fn $name(cfg: &WorldSampleConfig, x: i32, z: i32) -> $value {
            let found = CACHE.with(|cache| {
                let mut c = cache.borrow_mut();
                if c.cfg != Some(*cfg) {
                    *c = Cache {
                        cfg: Some(*cfg),
                        ..Default::default()
                    };
                }
                c.$field.get(&(x, z)).copied()
            });
            if let Some(value) = found {
                return value;
            }
            let value = $calculate(cfg, x, z);
            CACHE.with(|cache| {
                let mut c = cache.borrow_mut();
                if c.$field.len() >= $limit {
                    c.$field.clear();
                }
                c.$field.insert((x, z), value);
            });
            value
        }
    };
}
// A 34x34 padded chunk consumes 1156 columns. The previous 8192-entry cap
// covered about seven chunks per worker and cleared wholesale, which forced
// repeated climate/erosion work while a worker walked a terrain frontier.
cached!(
    column,
    columns,
    ColumnSample,
    super::sample_column_uncached,
    32_768
);
cached!(
    tree,
    trees,
    Option<TreeProfile>,
    super::tree_profile_uncached,
    4096
);
cached!(
    bush,
    bushes,
    Option<BushProfile>,
    super::bush_profile_uncached,
    4096
);
cached!(deadwood, deadwood, Option<FallenTrunk>, super::deadwood::profile, 512);
// A placement cell repeats through every voxel above it, including empty sky.
// Bound both accepted and rejected sites; the shared config reset covers seed,
// generator version, scale, world type and planet parameters.
cached!(flora_tree, flora_trees, Option<super::flora::TreeSite>, super::flora::tree_site, 4096);

/// Every chunk in a vertical stack reads the same padded column footprint, but
/// the stack is generated by different workers at different times, so the
/// per-worker column map above mostly missed. A sky chunk spent a third of its
/// time resampling columns its neighbours had already sampled.
type FootprintKey = (i32, i32, i32);
type Columns = Arc<[ColumnSample]>;
/// One footprint under construction. Every worker that wants it claims rows
/// from `next` until none are left; `rows` holds each finished row.
struct FootprintBuild {
    next: AtomicUsize,
    rows: Box<[OnceLock<Box<[ColumnSample]>>]>,
    done: Mutex<Option<Columns>>,
}

struct Footprints {
    cfg: Option<WorldSampleConfig>,
    recent: FastMap<FootprintKey, Columns>,
    older: FastMap<FootprintKey, Columns>,
    building: Vec<(WorldSampleConfig, FootprintKey, Weak<FootprintBuild>)>,
}
// 52-byte columns, 1156 per padded footprint: two generations of 384 is 46 MiB.
const FOOTPRINT_GENERATION: usize = 384;
static FOOTPRINTS: Mutex<Footprints> = Mutex::new(Footprints {
    cfg: None,
    recent: FastMap::with_hasher(FastBuild::new()),
    older: FastMap::with_hasher(FastBuild::new()),
    building: Vec::new(),
});

/// Columns `origin + (x, z)` for `0..size` in z-major order, or `None` when
/// cancelled. The shared cache lock is released before sampling.
pub(super) fn footprint(
    cfg: &WorldSampleConfig,
    origin_x: i32,
    origin_z: i32,
    size: i32,
    cancelled: &AtomicBool,
) -> Option<Arc<[ColumnSample]>> {
    if cancelled.load(Ordering::Relaxed) {
        return None;
    }
    let key = (origin_x, origin_z, size);
    let build = {
        let mut cache = FOOTPRINTS.lock().unwrap_or_else(|err| err.into_inner());
        if cache.cfg == Some(*cfg) {
            if let Some(found) = cache.recent.get(&key) {
                return Some(Arc::clone(found));
            }
            if let Some(found) = cache.older.remove(&key) {
                cache.recent.insert(key, Arc::clone(&found));
                return Some(found);
            }
        }

        // Register the miss before unlocking so vertical siblings in the
        // same batch can share the samples from a single worker.
        cache.building.retain(|(_, _, weak)| weak.strong_count() != 0);
        if let Some(build) = cache.building.iter().find_map(|(world, coord, weak)| {
            if *world == *cfg && *coord == key { weak.upgrade() } else { None }
        }) {
            build
        } else {
            let build = Arc::new(FootprintBuild {
                next: AtomicUsize::new(0),
                rows: (0..size).map(|_| OnceLock::new()).collect(),
                done: Mutex::new(None),
            });
            cache.building.push((*cfg, key, Arc::downgrade(&build)));
            build
        }
    };

    let row = |z: usize| -> Box<[ColumnSample]> {
        (0..size).map(|x| column(cfg, origin_x + x, origin_z + z as i32)).collect()
    };
    // Rows are a pure function of (cfg, x, z), so which worker samples one
    // does not matter. A worker cancelled mid-row leaves its claim unset.
    loop {
        if cancelled.load(Ordering::Relaxed) {
            return None;
        }
        let z = build.next.fetch_add(1, Ordering::Relaxed);
        if z >= build.rows.len() {
            break;
        }
        let _ = build.rows[z].set(row(z));
    }
    // Rows still unset were claimed by a worker that is mid-row or was
    // cancelled. Sample them here: at most one row per other worker.
    for (z, slot) in build.rows.iter().enumerate() {
        if slot.get().is_none() {
            if cancelled.load(Ordering::Relaxed) {
                return None;
            }
            let _ = slot.set(row(z));
        }
    }
    let mut result = build.done.lock().unwrap_or_else(|err| err.into_inner());
    if let Some(columns) = result.as_ref() {
        return Some(Arc::clone(columns));
    }
    let mut columns = Vec::with_capacity((size * size) as usize);
    for slot in build.rows.iter() {
        columns.extend_from_slice(slot.get()?);
    }
    let columns: Columns = columns.into();
    *result = Some(Arc::clone(&columns));
    if let Ok(mut f) = FOOTPRINTS.lock() {
        if f.cfg != Some(*cfg) {
            f.cfg = Some(*cfg);
            f.recent.clear();
            f.older.clear();
        }
        if f.recent.len() >= FOOTPRINT_GENERATION {
            f.older = std::mem::take(&mut f.recent);
        }
        f.recent.insert(key, Arc::clone(&columns));
    }
    Some(columns)
}
