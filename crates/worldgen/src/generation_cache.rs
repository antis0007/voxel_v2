//! Bounded generation caches: per-worker maps plus one shared map of chunk
//! column footprints. No locks are held while evaluating dependencies.
use super::{BushProfile, ColumnSample, TreeProfile, WorldSampleConfig};
use std::cell::RefCell;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Mutex};
use engine_core::fast_hash::{FastBuild, FastMap};

#[derive(Default)]
struct Cache {
    cfg: Option<WorldSampleConfig>,
    columns: FastMap<(i32, i32), ColumnSample>,
    trees: FastMap<(i32, i32), Option<TreeProfile>>,
    bushes: FastMap<(i32, i32), Option<BushProfile>>,
}
thread_local! { static CACHE: RefCell<Cache> = RefCell::new(Cache::default()); }

macro_rules! cached {
    ($name:ident, $field:ident, $value:ty, $calculate:path, $limit:expr) => {
        pub(super) fn $name(cfg: &WorldSampleConfig, x: i32, z: i32) -> $value {
            let found = CACHE.with(|cache| {
                let mut c = cache.borrow_mut();
                if c.cfg != Some(*cfg) {
                    *c = Cache {
                        cfg: Some(*cfg),
                        ..Default::default()
                    };
                }
                c.$field.get(&(x, z)).copied()
            });
            if let Some(value) = found {
                return value;
            }
            let value = $calculate(cfg, x, z);
            CACHE.with(|cache| {
                let mut c = cache.borrow_mut();
                if c.$field.len() >= $limit {
                    c.$field.clear();
                }
                c.$field.insert((x, z), value);
            });
            value
        }
    };
}
// A 34x34 padded chunk consumes 1156 columns. The previous 8192-entry cap
// covered about seven chunks per worker and cleared wholesale, which forced
// repeated climate/erosion work while a worker walked a terrain frontier.
cached!(
    column,
    columns,
    ColumnSample,
    super::sample_column_uncached,
    32_768
);
cached!(
    tree,
    trees,
    Option<TreeProfile>,
    super::tree_profile_uncached,
    4096
);
cached!(
    bush,
    bushes,
    Option<BushProfile>,
    super::bush_profile_uncached,
    4096
);

/// Every chunk in a vertical stack reads the same padded column footprint, but
/// the stack is generated by different workers at different times, so the
/// per-worker column map above mostly missed. A sky chunk spent a third of its
/// time resampling columns its neighbours had already sampled.
struct Footprints {
    cfg: Option<WorldSampleConfig>,
    recent: FastMap<(i32, i32, i32), Arc<[ColumnSample]>>,
    older: FastMap<(i32, i32, i32), Arc<[ColumnSample]>>,
}
// 52-byte columns, 1156 per padded footprint: two generations of 384 is 46 MiB.
const FOOTPRINT_GENERATION: usize = 384;
static FOOTPRINTS: Mutex<Footprints> = Mutex::new(Footprints {
    cfg: None,
    recent: FastMap::with_hasher(FastBuild::new()),
    older: FastMap::with_hasher(FastBuild::new()),
});

/// Columns `origin + (x, z)` for `0..size` in z-major order, or `None` when
/// cancelled. The lock is never held while sampling.
pub(super) fn footprint(
    cfg: &WorldSampleConfig,
    origin_x: i32,
    origin_z: i32,
    size: i32,
    cancelled: &AtomicBool,
) -> Option<Arc<[ColumnSample]>> {
    let key = (origin_x, origin_z, size);
    if let Ok(mut f) = FOOTPRINTS.lock()
        && f.cfg == Some(*cfg)
    {
        if let Some(found) = f.recent.get(&key) {
            return Some(Arc::clone(found));
        }
        if let Some(found) = f.older.remove(&key) {
            f.recent.insert(key, Arc::clone(&found));
            return Some(found);
        }
    }
    let mut columns = Vec::with_capacity((size * size) as usize);
    for z in 0..size {
        if cancelled.load(Ordering::Relaxed) {
            return None;
        }
        for x in 0..size {
            columns.push(column(cfg, origin_x + x, origin_z + z));
        }
    }
    let columns: Arc<[ColumnSample]> = columns.into();
    if let Ok(mut f) = FOOTPRINTS.lock() {
        if f.cfg != Some(*cfg) {
            *f = Footprints { cfg: Some(*cfg), recent: FastMap::default(), older: FastMap::default() };
        }
        if f.recent.len() >= FOOTPRINT_GENERATION {
            f.older = std::mem::take(&mut f.recent);
        }
        f.recent.insert(key, Arc::clone(&columns));
    }
    Some(columns)
}
