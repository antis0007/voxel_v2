import { validatorBuilds } from "./catalog-contracts.mjs";
import * as fs from "node:fs";
import path from "node:path";
import { spawn, spawnSync } from "node:child_process";
import { root, ensureDirectory } from "./workspace.mjs";
import { nativeSourceFingerprint, validatorDirectory, binaryName, hashBytes } from "./native-content-validation.mjs";

// Explicit build step: a save never launches Cargo or silently skips validation.
const before = nativeSourceFingerprint(root);
const target = path.resolve(process.env.CARGO_TARGET_DIR || path.join(root, "target"));
const examples = validatorBuilds;
const names = examples.map(([, name]) => name);
for (const [crate, example] of examples) {
  await new Promise((resolve, reject) => {
    const child = spawn("cargo", ["build", "--locked", "--offline", "-p", crate, "--example", example,
      "--target-dir", target], { cwd: root, stdio: "inherit", windowsHide: true });
    child.once("error", reject);
    child.once("close", code => code === 0 ? resolve() : reject(new Error("Native validator build failed (" + code + ")")));
  });
}
if (nativeSourceFingerprint(root) !== before) throw new Error("Native sources changed during the build. Run it again.");
const directory = ensureDirectory(validatorDirectory(root));
const receipt = { version: 1, source: before, binaries: {} };
for (const name of names) {
  const bytes = fs.readFileSync(path.join(target, "debug", "examples", binaryName(name)));
  receipt.binaries[name] = hashBytes(bytes);
  const temporary = path.join(directory, binaryName(name) + ".building");
  fs.writeFileSync(temporary, bytes, { mode: 0o755 });
  fs.renameSync(temporary, path.join(directory, binaryName(name)));
}
const descriptor = spawnSync(path.join(directory, binaryName("check_fabrication")), ["--describe"],
  { cwd: root, encoding: "utf8", windowsHide: true, timeout: 10000 });
if (descriptor.status !== 0 || descriptor.error) throw new Error("Fabrication metadata export failed");
const metadata = JSON.parse(descriptor.stdout);
if (metadata.version !== 1 || metadata.resources?.length !== metadata.resourceCount) throw new Error("Invalid fabrication descriptor");
const metadataText = "// Generated by build-validators.mjs from check_fabrication --describe. Do not edit.\nconst metadata = "
  + JSON.stringify(metadata, null, 2) + ";\nObject.freeze(metadata.resources);\nexport default Object.freeze(metadata);\n";
const metadataFile = path.join(root, "tools/axiom-dev/fabrication-contract.mjs");
const metadataTemporary = metadataFile + ".building";
fs.writeFileSync(metadataTemporary, metadataText);
fs.renameSync(metadataTemporary, metadataFile);
receipt.fabricationMetadata = { file: hashBytes(metadataText), data: hashBytes(JSON.stringify(metadata)) };
const temporary = path.join(directory, "receipt.building.json");
fs.writeFileSync(temporary, JSON.stringify(receipt, null, 2));
fs.renameSync(temporary, path.join(directory, "receipt.json"));
console.log("Native content validators are ready for this source revision.");
