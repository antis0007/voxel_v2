import test from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import contract from "./fabrication-contract.mjs";
import { checkedValidator, hashBytes, validateNativeContent, validateNativeBundle } from "./native-content-validation.mjs";
import { fabricationRows } from "./fabrication-data.mjs";
import { copyNativeFixture } from "./workshop-test-fixture.mjs";
import { nativeTuning } from "./workshop-planning.mjs";
import { parse } from "./syntax.mjs";

const source = fileURLToPath(new URL("../../", import.meta.url));
const catalog = "assets/fabrication.ron";
const text = readFileSync(path.join(source, catalog), "utf8");
const changeOutput = (resource, count = 64) => {
  const tree = parse(text, "ron"), node = tree.children[0].children.find(node => node.key === "output");
  return text.slice(0, node.start) + `(${resource}, ${count})` + text.slice(node.end);
};
function fixture(t) {
  const root = mkdtempSync(path.join(tmpdir(), "axiom-fabrication-check-"));
  t.after(() => { assert.equal(path.dirname(root), tmpdir()); rmSync(root, { recursive: true, force: true }); });
  copyNativeFixture(source, root);
  mkdirSync(path.join(root, "assets"), { recursive: true });
  writeFileSync(path.join(root, catalog), text);
  return root;
}

test("generated browser metadata exactly matches native descriptor", () => {
  const binary = checkedValidator(source, catalog);
  const result = spawnSync(binary, ["--describe"], { encoding: "utf8", windowsHide: true });
  assert.equal(result.status, 0);
  assert.deepEqual(JSON.parse(result.stdout), contract);
  assert.equal(contract.resources.at(-1), "Feathers");
  assert.equal(contract.resourceCount, 25);
});

test("native and Forge accept feathers and reject unregistered resource IDs", () => {
  assert.equal(validateNativeContent(source, catalog, changeOutput(24)).valid, true);
  assert.equal(fabricationRows(changeOutput(24))[0].output[0], 24);
  assert.deepEqual(nativeTuning({ output: [24, 1] }).output, [24, 64]);
  for (const invalid of [25, 255]) {
    assert.throws(() => validateNativeContent(source, catalog, changeOutput(invalid)), /Native validation rejected/);
    assert.throws(() => fabricationRows(changeOutput(invalid)), /resource ID/);
    assert.throws(() => nativeTuning({ output: [invalid, 1] }), /resource ID/);
  }
});

test("edited generated bytes invalidate the publication receipt", t => {
  const root = fixture(t), file = path.join(root, "tools/axiom-dev/fabrication-contract.mjs");
  writeFileSync(file, readFileSync(file, "utf8") + "\n// changed\n");
  assert.throws(() => checkedValidator(root, catalog), /missing or stale/);
});

test("a fresh file hash cannot conceal stale metadata already loaded in the server", t => {
  const root = fixture(t), file = path.join(root, "tools/axiom-dev/fabrication-contract.mjs");
  const receiptPath = path.join(root, "target/axiom-dev/native-validation/receipt.json");
  const next = { ...contract, maxPower: contract.maxPower - 1 };
  const bytes = "export default " + JSON.stringify(next) + ";\n";
  writeFileSync(file, bytes);
  const receipt = JSON.parse(readFileSync(receiptPath, "utf8"));
  receipt.fabricationMetadata = { file: hashBytes(bytes), data: hashBytes(JSON.stringify(next)) };
  writeFileSync(receiptPath, JSON.stringify(receipt));
  assert.throws(() => checkedValidator(root, catalog), /missing or stale/);
});

test("metadata and process drafts cannot publish in the same bundle", () => {
  const change = relative => ({ relative, original: Buffer.from("before"), next: Buffer.from("after") });
  assert.throws(() => validateNativeBundle(source, [change(catalog), change("tools/axiom-dev/fabrication-contract.mjs")]), /unpublished native schema/);
});
