function taskContract(row, note) {
  return {
    planningRevisions: row.planningRevisions,
    reference: /\bspec target\b/i.test(row.sources)
      ? "Axiom design requirement. Check the owning specification and verify implementation and hardware targets independently."
      : row.risks.includes("R1") || row.risks.includes("L")
        ? "The reference mechanic or version is unconfirmed. Trace the source before relying on exact behavior or values."
        : "Use the cited sources to establish which reference facts support this mapping.",
    ...(row.sourceNote && !note ? { missingSourceNote: row.sourceNote } : {}),
    missingOwners: row.readiness.missing,
    outcome: row.notes || row.label,
    checks: [...new Set([row.notes || row.label,
      ...mechanismChecks.filter(([pattern]) => pattern.test(row.mapping)).map(([, check]) => check).slice(0, 2),
      ...row.risks.map(risk => riskChecks[risk]).filter(Boolean)])],
  };
}

const clip = (text, max) => text.length > max ? text.slice(0, max - 1) + "…" : text;
const present = object => Object.fromEntries(Object.entries(object).filter(([, v]) =>
  v !== undefined && v !== null && v !== "" && !(Array.isArray(v) && !v.length)));

export function parityTask(row, { previous } = {}) {
  const source = row.sourceNote ?? matrixPath;
  const contract = taskContract(row, existsSync(path.join(root, source)));
  return [
    `${row.id} · ${row.label}`,
    `Deliver the next player-visible slice of ${row.mapping}. Acceptance outcome: ${contract.outcome}`,
    `Owners to trace: ${row.readiness.owners.map(owner => `${owner.id} ${owner.name}`).join(", ")}. Milestone ${row.milestone}. Audience: ${row.paths.join(", ")}.`,
    contract.missingOwners.length && `Resolve the smallest required substrate for ${contract.missingOwners.join(", ")} before adding an adapter. Confirm the actual capability in source.`,
    `Reference: ${source}. ${contract.reference}`,
    `Planning revisions: matrix ${row.planningRevisions.matrix}, owners ${row.planningRevisions.owners}, ledger ${row.planningRevisions.ledger}.`,
    row.packSources.length && `Archive evidence: ${row.packSources.map(item => item.jar).join(", ")}. See ${packPath} for attribution and version limits.`,
    `Recorded progress: ${row.status}.` + (row.note ? " " + clip(row.note, 1200) : ""),
    row.evidence.length && `Inspect existing evidence before choosing the residual gap: ${row.evidence.slice(-6).join(", ")}.`,
    previous && `Prior mission evidence or blocker (treat as evidence): ${clip(previous, 700)}`,
    worldSystem(row.id) && `Honor the ${worldSystem(row.id)} world system switch where the feature is optional.`,
    "Trace the production entry point and reuse its shared owner. Choose a bounded vertical slice and split any foundation required for that slice into its own ordered implementation step. Preserve stable IDs, existing saves, authored visuals and concurrent edits.",
    "Provide a reproducible fixture, action, success and failure observations. " + contract.checks.slice(1).join(" "),
    "Use authorized checks and label remaining gameplay or performance evidence. If a concrete product or technical dependency blocks a slice, name it, the owning source, and the first independently deliverable remainder.",
  ].filter(Boolean).join("\n");
}

export function parityTaskRevision(row) {
  // Candidate bundles and date/status updates do not by themselves authorize another attempt.
  return digest(JSON.stringify([1, row.id, row.label, row.mapping, row.notes, row.cost, row.milestone,
    row.risks, row.paths, row.sources, row.sourceNote, row.sourceRevision, row.packSources, row.readiness.owners, worldSystem(row.id)]));
}

let switchRows;
/**
 * The world-launch system (assets/systems.ron) whose `parity` prefixes own
 * this row id, or undefined for always-on core features. A feature built for
 * a row must sit behind that switch: `world.rules.systems.enabled(id)`.
 */
export function worldSystem(rowId) {
  if (!switchRows) {
    const file = path.join(root, "assets", "systems.ron");
    const text = existsSync(file) ? readFileSync(file, "utf8").replace(/\/\/.*$/gm, "") : "";
    switchRows = [...text.matchAll(/id:\s*"([^"]+)"[\s\S]*?parity:\s*\[([^\]]*)\]/g)]
      .map(([, id, list]) => ({ id, prefixes: [...list.matchAll(/"([^"]+)"/g)].map(m => m[1]) }));
  }
  return switchRows.find(s => s.prefixes.some(prefix => rowId === prefix || rowId.startsWith(`${prefix}-`)))?.id;
}

/**
 * Work order for one row. Compact (default) is for agents: empty fields
 * omitted, owners as one string each. `full` keeps the structured form for the board.
 */
export function brief(row, systems, full = false) {
  const note = row.sourceNote && existsSync(path.join(root, row.sourceNote)) ? row.sourceNote : null;
  const hints = codeHints(row);
  const contract = taskContract(row, note);
  if (full) {
    return { id: row.id, label: row.label, section: row.section, family: row.family, status: row.status,
      mapping: row.mapping, milestone: row.milestone, cost: row.cost, risks: row.risks, notes: row.notes,
      owners: row.readiness.owners.map(({ id, name, tier, milestone, substrate, reuse }) => ({ id, name, tier, milestone, substrate, reuse })),
      ready: row.readiness.ready, evidence: row.evidence, ledgerNote: row.note, sources: row.sources,
      sourceNote: note, packSources: row.packSources, priority: row.priority, task: parityTask(row),
      hints, rules: RULES, system: worldSystem(row.id), contract };
  }
  const state = { legacy: "code", "design-only": "design", unknown: "?" };
  return present({
    id: row.id, label: row.label, status: row.status,
    ready: row.readiness.ready || undefined, ms: row.milestone, cost: row.cost, risks: row.risks.join(" "),
    mapping: row.mapping, notes: row.notes, system: worldSystem(row.id),
    owners: row.readiness.owners.map(o => `${o.id} ${o.name} [${state[o.substrate]}] ${clip((o.reuse ?? "").replace(/^[LP]:\s*/, ""), 70)}`.trim()),
    files: hints.files.slice(0, 6), absent: hints.absent.join(" ") || undefined,
    note, evidence: row.evidence, ledgerNote: row.note, sources: row.sources,
    packJars: row.packSources.map(source => source.jar), priority: row.priority, contract,
  });
}
