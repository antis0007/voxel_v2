const cells = line => line.slice(1, line.endsWith("|") ? -1 : undefined).split(/(?<!\\)\|/).map(cell => cell.trim());
const listOf = text => text.split(/[,\s]+/).map(part => part.trim()).filter(part => part && part !== "—");
const read = relative => readFileSync(path.join(root, relative), "utf8");
const digest = text => createHash("sha256").update(text).digest("hex").slice(0, 16);

export function parseMatrix(text) {
  const rows = [];
  let section = "";
  for (const line of text.split(/\r?\n/)) {
    if (line.startsWith("## ")) { section = line.slice(3).trim(); continue; }
    if (!line.startsWith("| ")) continue;
    const parts = cells(line);
    const head = parts[0]?.match(/^([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*):\s*(.+)$/);
    if (!head || parts.length < 10) continue;
    const note = parts[1].match(/\[source note\]\(([^)]+)\)/)?.[1];
    rows.push({
      id: head[1], label: head[2].replace(/`\[unverified\]`/g, "").trim(), section,
      sources: parts[1].replace(/;\s*\[source note\]\([^)]+\)/, "").replace(/\[([^\]]+)\]\([^)]+\)/g, "$1"),
      family: parts[1].split(";")[0].trim(),
      sourceNote: note ? "docs/research/" + note : null,
      mapping: parts[2], depends: listOf(parts[3]), cost: parts[4],
      pillars: listOf(parts[5]), paths: listOf(parts[6]), milestone: parts[7],
      risks: listOf(parts[8]), notes: parts[9] ?? "",
    });
  }
  return rows;
}

export function parseSystems(text) {
  const systems = new Map();
  for (const line of text.split(/\r?\n/)) {
    if (!/^\| [A-Z]\d{2} \|/.test(line)) continue;
    const [id, name, tier, milestone, prerequisites, reuse] = cells(line);
    systems.set(id, { id, name, tier, milestone, prerequisites: listOf(prerequisites ?? ""),
      reuse: reuse ?? "", substrate: /^L:/.test(reuse ?? "") ? "legacy" : /^P:/.test(reuse ?? "") ? "design-only" : "unknown" });
  }
  return systems;
}

export function readStatus() {
  const file = path.join(root, statusPath);
  const text = existsSync(file) ? readFileSync(file, "utf8") : "";
  const data = text ? JSON.parse(text) : { version: 1, rows: {} };
  return { data, revision: digest(text || "{}") };
}

/** Revision-checked, atomic status write. Unknown IDs and states are refused. */
export function writeStatus(id, change, revision, known) {
  const file = path.join(root, statusPath), lock = file + ".lock";
  let fd;
  try { fd = openSync(lock, "wx"); }
  catch (error) {
    if (error.code === "EEXIST") throw Object.assign(new Error("Parity status is being updated. Reload before retrying."), { status: 409 });
    throw error;
  }
  const temporary = file + "." + randomUUID() + ".tmp";
  try {
    const { data, revision: current } = readStatus();
    if (revision !== current) throw Object.assign(new Error(`Status file changed (revision ${current}); reload before writing`), { status: 409 });
    if (!known.has(id)) throw new Error("Unknown feature ID " + id);
    if (change.status && !STATUSES.includes(change.status)) throw new Error("Status must be one of " + STATUSES.join(", "));
    const before = data.rows[id] ?? { status: "open", evidence: [] };
    const evidence = [...new Set([...(before.evidence ?? []), ...(change.evidence ?? [])])];
    for (const entry of (change.evidence ?? [])) {
      const evidenceFile = entry.split("#")[0];
      if (!/^(?:https?:|commit:)/.test(entry) && !existsSync(path.join(root, evidenceFile))) throw new Error("Evidence path not found: " + entry);
    }
    if (change.status === "verified" && !evidence.length) throw new Error("verified needs at least one evidence path or commit:");
    const next = { ...before, ...change, evidence, updated: new Date().toISOString().slice(0, 10) };
    if (!next.note) delete next.note;
    data.rows[id] = next;
    data.rows = Object.fromEntries(Object.entries(data.rows).sort(([a], [b]) => a.localeCompare(b)));
    writeFileSync(temporary, JSON.stringify(data, null, 2) + "\n", { flag: "wx" });
    renameSync(temporary, file);
    return { id, before, after: next, revision: readStatus().revision };
  } finally {
    rmSync(temporary, { force: true });
    closeSync(fd);
    rmSync(lock);
  }
}

export function familiesOf(row) {
  return Object.entries(FAMILIES).filter(([, family]) => family.ids.test(row.id) || family.match.test(row.sources)).map(([key]) => key);
}

/** Inventory signal only. A legacy entry identifies code to inspect. */
export function readiness(row, systems) {
  const owners = row.depends.map(id => systems.get(id) ?? { id, name: "unknown system", substrate: "unknown" });
  const missing = owners.filter(owner => owner.substrate !== "legacy").map(owner => owner.id);
  return { owners, missing, ready: !missing.length };
}

export function loadLedger() {
  const matrixText = read(matrixPath);
  const planText = read(planPath);
  const engineText = existsSync(path.join(root, engineMatrixPath)) ? read(engineMatrixPath) : "";
  const modRows = parseMatrix(matrixText), modIds = new Set(modRows.map(row => row.id));
  const autoText = existsSync(path.join(root, autoMatrixPath)) ? read(autoMatrixPath) : "";
  const engineOwn = parseMatrix(engineText);
  // Generated rows must never stop the swarm: skip any whose id is invalid or already taken.
  const taken = new Set([...modIds, ...engineOwn.map(row => row.id)]);
  // `generated` marks rows the swarm made for itself (rule-scan chores, performance targets); the swarm owns them.
  const autoRows = parseMatrix(autoText).filter(row => isEngineRow(row) && !taken.has(row.id) && taken.add(row.id))
    .map(row => ({ ...row, generated: true }));
  const engineRows = [...engineOwn, ...autoRows];
  const seen = new Set();
  for (const row of engineRows) {
    if (!isEngineRow(row) || modIds.has(row.id) || seen.has(row.id)) throw new Error(`Invalid or duplicate engine row ${row.id} in ${engineMatrixPath}`);
    seen.add(row.id);
  }
  const rows = [...modRows, ...engineRows];
  const engineRevision = digest(engineText);
  const systems = parseSystems(planText);
  const { data, revision } = readStatus();
  const packText = existsSync(path.join(root, packPath)) ? read(packPath) : "";
  const pack = packText ? JSON.parse(packText) : { jars: [] };
  const references = new Map();
  const known = new Set(rows.map(row => row.id));
  for (const { jar, features, note } of pack.jars) for (const id of features) {
    if (!known.has(id)) throw new Error(`Unknown parity feature ${id} in ${packPath}`);
    if (!references.has(id)) references.set(id, []);
    references.get(id).push({ jar, note });
  }
  const planningRevisions = { matrix: digest(matrixText), owners: digest(planText), ledger: revision };
  const noteRevisions = new Map();
  const ledger = rows.map(row => {
    // Rows under an "Epics" heading need an owner-led design session first, so workers skip them by default.
    const state = data.rows[row.id] ?? { status: /^Epics\b/i.test(row.section) ? "design" : "open", evidence: [] };
    const packSources = references.get(row.id) ?? [];
    const families = familiesOf(row);
    if (packSources.length && !families.includes("pack2020")) families.push("pack2020");
    if (row.sourceNote && !noteRevisions.has(row.sourceNote))
      noteRevisions.set(row.sourceNote, existsSync(path.join(root, row.sourceNote)) ? digest(read(row.sourceNote)) : null);
    return { ...row, families, packSources, status: state.status, evidence: state.evidence ?? [], note: state.note,
      updated: state.updated, readiness: readiness(row, systems),
      planningRevisions: isEngineRow(row) ? { ...planningRevisions, matrix: engineRevision } : planningRevisions,
      sourceRevision: noteRevisions.get(row.sourceNote) };
  });
  const demand = new Map();
  for (const row of ledger.filter(row => !["verified", "parked"].includes(row.status))) {
    for (const id of row.depends) demand.set(id, (demand.get(id) ?? 0) + 1);
  }
  for (const row of ledger) row.priority = priority(row, demand);
  return { rows: ledger, systems, revision, matrixRevision: planningRevisions.matrix, planningRevisions, packRevision: digest(packText) };
}

export function filterRows(rows, { family, status, milestone, ready, query, section } = {}) {
  const words = (query ?? "").toLowerCase().split(/\s+/).filter(Boolean);
  const families = family ? family.split(",").flatMap(name => name === "industrial" ? INDUSTRIAL : [name]) : [];
  // Without a family or a query, engine rows stay out: "all" keeps meaning the mod-parity ledger,
  // and workers reach engine work only through an engine family (engine, engperf, engsim, ...).
  return rows.filter(row => (families.length ? row.families.some(name => families.includes(name)) : words.length > 0 || !isEngineRow(row))
    && (!status || status.split(",").includes(row.status))
    && (!milestone || row.milestone.split(/[ /]+/).includes(milestone))
    && (ready === undefined || row.readiness.ready === ready)
    && (!section || row.section.toLowerCase().includes(section.toLowerCase()))
    && words.every(word => [row.id, row.label, row.sources, row.mapping, row.notes, ...(row.packSources ?? []).map(source => source.jar)].join(" ").toLowerCase().includes(word)));
}

function priority(row, demand) {
  const milestone = Number(row.milestone.match(/M(\d+(?:\.\d+)?)/)?.[1] ?? 9);
  const shared = row.cost.startsWith("N(") ? Math.min(24, Math.floor(Math.max(0, ...row.depends.map(id => demand.get(id) ?? 0)) / 3)) : 0;
  const factors = { milestone: (9 - milestone) * 8, owners: row.readiness.ready ? 16 : -4 * row.readiness.missing.length,
    progress: { building: 12, playable: 8, open: 4, design: 2, blocked: -30, verified: -100, parked: -100 }[row.status] ?? 0,
    shared, pack: row.families.includes("pack2020") ? 8 : 0,
    risk: -row.risks.filter(risk => !["R1", "L"].includes(risk)).length * 2 };
  return { score: Object.values(factors).reduce((sum, value) => sum + value, 0), factors };
}

export function comparePriority(a, b) {
  return b.priority.score - a.priority.score || a.id.localeCompare(b.id, undefined, { numeric: true });
}

/** Include prerequisite, implementation and evidence work from all families. */
export function nextRows(rows, limit = 5) {
  return rows.filter(row => !["verified", "parked"].includes(row.status)).sort(comparePriority).slice(0, limit);
}

const STOP = new Set("with from that this into their shared each other where which about using under over more than only also have when these those across without between through".split(" "));
/** Where the repo may already implement part of a row: bounded keyword search over content tables and factory code. */
const SCOPE = ["assets", "crates/app/src/world/factory", "crates/app/src/world/inventory.rs", "crates/content/src"];
const GENERIC = 30; // a word found in more files than this is too common to locate anything
export function codeHints(row, max = 10) {
  const terms = (text, weight) => (text.toLowerCase().match(/[a-z][a-z-]{4,}/g) ?? [])
    .filter(word => !STOP.has(word)).map(word => [word.replace(/s$/, ""), weight]);
  const weights = new Map();
  for (const [word, weight] of [...terms(row.label, 2), ...terms(row.mapping, 1)]) weights.set(word, Math.max(weights.get(word) ?? 0, weight));
  const words = [...weights.keys()].slice(0, 8);
  // A row may name its owner files in backticks; those lead, and engine rows rely on them
  // because the keyword search below only covers content tables and factory code.
  const explicit = [...new Set([...`${row.notes} ${row.mapping}`.matchAll(/`([\w./-]+\.(?:rs|ron|wgsl|toml))`/g)].map(m => m[1]))]
    .filter(file => !file.includes("..") && existsSync(path.join(root, file)));
  if (!words.length || isEngineRow(row)) return { words: [], absent: [], files: explicit.slice(0, max) };
  // One pass: every "path:match" line tells which words each file contains.
  let out = "";
  try {
    out = execFileSync("rg", ["-i", "-o", "-F", "--no-line-number", "--with-filename", "-g", "*.rs", "-g", "*.ron",
      "-g", "!assets/art_direction/**", "-g", "!assets/source/**", ...words.flatMap(word => ["-e", word]), ...SCOPE],
    { cwd: root, encoding: "utf8", timeout: 6000, maxBuffer: 16 << 20 });
  } catch (error) { out = error.stdout ?? ""; }
  const filesOf = new Map(words.map(word => [word, new Set()]));
  for (const line of out.split(/\r?\n/)) {
    const at = line.lastIndexOf(":");
    if (at > 0) filesOf.get(line.slice(at + 1).toLowerCase())?.add(line.slice(0, at).replaceAll("\\", "/"));
  }
  const score = new Map();
  const used = words.filter(word => filesOf.get(word).size && filesOf.get(word).size <= GENERIC);
  for (const word of used) for (const file of filesOf.get(word)) {
    // Factory code and machine/recipe tables beat unrelated content tables and tests.
    const place = /_tests\.rs$|\/tests(\.rs|\/)/.test(file) ? 0.4
      : /^crates\/app\/src\/world\/factory|^assets\/(machines|recipes|reactions|materials|fabrication)\.ron/.test(file) ? 1.5
      : file.startsWith("assets/") ? 0.6 : 1;
    score.set(file, (score.get(file) ?? 0) + weights.get(word) * place);
  }
  const files = [...new Set([...explicit, ...[...score].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([file]) => file)])].slice(0, max);
  return { words: used, absent: words.filter(word => !filesOf.get(word).size), files };
}

/**
 * Gather Context hook: briefs for feature IDs named in a task (at most 3).
 * Never throws; a missing or malformed matrix yields no parity context.
 */
export function parityContext(task) {
  const named = [...new Set(String(task).toUpperCase().match(/\b(?:L\d{3}|[A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*-\d{2,3})\b/g) ?? [])];
  if (!named.length) return undefined;
  try {
    const ledger = loadLedger();
    const rows = named.map(id => ledger.rows.find(row => row.id === id)).filter(Boolean).slice(0, 3)
      .map(row => brief(row, ledger.systems));
    return rows.length ? { rows, rules: RULES, scope: "Planning references. Confirm the implementation and its evidence on the actual source snapshot." } : undefined;
  } catch { return undefined; }
}

